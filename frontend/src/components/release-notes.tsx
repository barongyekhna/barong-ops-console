function MetricRow({ metric }: { metric: ReleaseMetric }) {
  return (
    <div className={styles.metric}>
      <span className={styles.metricLabel}>{metric.label}</span>
      <span className={styles.metricValues}>
        {metric.was ? (
          <>
            <span className={styles.was}>{metric.was}</span>
            <span aria-hidden="true" className={styles.arrow}>
              →
            </span>
          </>
        ) : null}
        <span className={styles.now}>{metric.now}</span>
      </span>
      {metric.note ? (
        <span className={styles.metricNote}>{metric.note}</span>
      ) : null}
    </div>
  );
}

